import { promises as fs } from 'fs';
import path from 'path';
import { execSync } from 'child_process';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const PRODUCTS = path.join(ROOT, 'src', 'app', 'data', 'products.ts');
const OUT = path.join(ROOT, 'public', 'sitemap.xml');
const REDIRECTS = path.join(ROOT, 'public', '_redirects');
const SITE_URL = 'https://www.ivycrew.co.in';

// Public, indexable routes from src/app/routes.ts. Cart, checkout, favorites,
// rewards and the hidden women's section are intentionally left out.
const PAGES = [
  '/', '/men', '/new-arrivals', '/best-sellers', '/sale',
  '/size-guide', '/shipping-returns', '/faq', '/contact',
  '/our-story', '/sustainability', '/store-locator',
  '/privacy-policy', '/terms-of-service',
];

// Last commit date for a path, or today if it has uncommitted changes.
function lastCommitDate(file) {
  try {
    const dirty = execSync(`git status --porcelain -- "${file}"`, { cwd: ROOT }).toString().trim();
    if (dirty) return new Date().toISOString().slice(0, 10);
    const iso = execSync(`git log -1 --format=%cs -- "${file}"`, { cwd: ROOT }).toString().trim();
    if (iso) return iso;
  } catch {}
  return new Date().toISOString().slice(0, 10);
}

// Must match getProductSlug() in src/app/data/products.ts.
const slugify = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

// Placeholder names used before TSHIRT_NAMES existed ("Classic Crew Tee 01" ...).
// Their slugs were live and submitted to Search Console, so they keep redirecting.
const LEGACY_NAME_POOL = [
  'Classic Crew Tee', 'Heritage Pocket Tee', 'Essential Cotton Tee', 'Vintage Wash Tee',
  'Tailored Fit Tee', 'Soft Touch Tee', 'Athletic Stripe Tee', 'Performance Active Tee',
  'Statement Graphic Tee', 'Modern Relaxed Tee', 'Premium Pima Tee', 'Refined Crew Tee',
];

// Mirrors how menTshirts builds id and name in products.ts.
async function menProducts() {
  const src = await fs.readFile(PRODUCTS, 'utf8');
  const count = src.match(/const menTshirts[^=]*=\s*Array\.from\(\{\s*length:\s*(\d+)/);
  const base = src.match(/id:\s*(\d+)\s*\+\s*n/);
  const list = src.match(/const TSHIRT_NAMES\s*=\s*\[([\s\S]*?)\];/);
  const names = list ? [...list[1].matchAll(/'([^']+)'/g)].map((m) => m[1]) : [];
  if (!count || !base || !names.length) {
    throw new Error('generate-sitemap: could not read menTshirts length / id base / TSHIRT_NAMES from products.ts');
  }
  if (names.length !== Number(count[1])) {
    throw new Error(`generate-sitemap: TSHIRT_NAMES has ${names.length} names but menTshirts has ${count[1]} products`);
  }
  const slugs = names.map(slugify);
  const dupes = slugs.filter((s, i) => slugs.indexOf(s) !== i);
  if (dupes.length) {
    throw new Error(`generate-sitemap: duplicate product slugs: ${[...new Set(dupes)].join(', ')}`);
  }
  return slugs.map((slug, i) => {
    const n = i + 1;
    const legacy = slugify(`${LEGACY_NAME_POOL[i % LEGACY_NAME_POOL.length]} ${String(n).padStart(2, '0')}`);
    return { id: Number(base[1]) + n, slug, legacy };
  });
}

async function main() {
  const siteDate = lastCommitDate('src');
  const productDate = lastCommitDate('src/app/data/products.ts');
  const products = await menProducts();
  const urls = [
    ...PAGES.map((p) => ({ loc: `${SITE_URL}${p}`, lastmod: siteDate })),
    ...products.map((p) => ({ loc: `${SITE_URL}/product/${p.slug}`, lastmod: productDate })),
  ];

  // Old numeric and placeholder-name product URLs 301 to their current URL.
  const redirects = [
    '# Generated by scripts/generate-sitemap.mjs — do not edit by hand.',
    ...products.map((p) => `/product/${p.id} /product/${p.slug} 301`),
    ...products.map((p) => `/product/${p.legacy} /product/${p.slug} 301`),
    '',
  ].join('\n');
  await fs.writeFile(REDIRECTS, redirects);

  const xml = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ...urls.map((u) => `  <url><loc>${u.loc}</loc><lastmod>${u.lastmod}</lastmod></url>`),
    '</urlset>',
    '',
  ].join('\n');

  await fs.writeFile(OUT, xml);
  console.log(`sitemap.xml: ${urls.length} URLs`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
